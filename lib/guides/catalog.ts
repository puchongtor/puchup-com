export type GuideTopicId = (typeof guideTopics)[number]["id"];

export function guideMatchesTopic(slug: string, topicId: GuideTopicId): boolean {
  const topic = guideTopics.find((t) => t.id === topicId);
  return topic ? (topic.slugs as readonly string[]).includes(slug) : false;
}

export function primaryTopicLabel(slug: string): string | undefined {
  const preferred: GuideTopicId[] = [
    "pricing",
    "clinic",
    "food",
    "auto",
    "line",
    "speed",
    "ai",
    "google",
    "basics",
  ];
  for (const id of preferred) {
    if (guideMatchesTopic(slug, id)) {
      return guideTopics.find((t) => t.id === id)?.label;
    }
  }
  return undefined;
}
